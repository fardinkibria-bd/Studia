// Build-time discovery of the website's focusing sounds.
//
// Scans the public/ folder for audio files with the .mp3 extension (directly
// inside public/, top level only) and writes src/data/sounds.generated.ts
// containing the root-relative URL of each one. Vite serves public assets at
// the root path, so the browser loads the actual files straight from public/
// — no hashing, copying, re-compression or relocation.
//
// alarm.mp3 is excluded: it is the Focus session-completion alarm played by
// AlarmContext, not an ambient focusing sound, so it never appears in the
// Focusing Sounds list.
//
// Runs automatically on every `vite` (dev/build/preview) start via the small
// plugin in vite.config.ts, or manually with `npm run refresh-sounds`.
// Adding an MP3 to public/ requires no code changes — just rerun.
import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));

/**
 * Files inside public/ that are NOT focusing sounds. alarm.mp3 is the Focus
 * session-completion alarm — it must never show up in the focusing-sounds
 * picker. Every other MP3 file in public/ is auto-discovered.
 */
const EXCLUDED_SOUND_FILES = new Set(['alarm.mp3']);

const HEADER = `// AUTO-GENERATED by scripts/generate-sounds-manifest.mjs — DO NOT EDIT.
// Regenerated automatically whenever \`vite\` (dev/build/preview) starts, or
// manually with \`npm run refresh-sounds\`. Add an MP3 to public/ and rerun.
`;

/**
 * Scan public/ (top level only) for .mp3 files, ignoring hidden files, nested
 * folders, and the excluded non-focusing sounds. Returns root-relative URLs
 * sorted by filename — with the display-name transformation used by the Focus
 * UI this equals sorting alphabetically by display name.
 */
export function discoverSoundFiles({ rootDir = projectRoot, exclude = EXCLUDED_SOUND_FILES } = {}) {
  const publicDir = join(rootDir, 'public');
  const names = readdirSync(publicDir, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isFile() &&
        !entry.name.startsWith('.') &&
        /\.mp3$/i.test(entry.name) &&
        !exclude.has(entry.name.toLowerCase()),
    )
    .map((entry) => entry.name)
    .sort();
  return names.map((name) => `/${name}`);
}

/**
 * Write the generated manifest. Never throws on missing public/ — an empty
 * manifest makes the Focus UI show its existing empty state gracefully.
 * Returns the number of sounds discovered.
 */
export function generateSoundsManifest({ rootDir = projectRoot } = {}) {
  let urls;
  try {
    urls = discoverSoundFiles({ rootDir });
  } catch (error) {
    console.error(`[sounds-manifest] Could not scan public/: ${error}`);
    urls = [];
  }
  const entries = urls.length
    ? urls.map((url) => `  '${url}',`).join('\n')
    : '  // No MP3 files found in public/ — the Focus UI shows its empty state.';
  const outputFile = join(rootDir, 'src', 'data', 'sounds.generated.ts');
  mkdirSync(dirname(outputFile), { recursive: true });
  writeFileSync(
    outputFile,
    `${HEADER}\n/** Root-relative URLs of every MP3 file directly inside public/. */\nexport const SOUND_FILES: readonly string[] = [\n${entries}\n];\n`,
    'utf8',
  );
  return urls.length;
}

// CLI entry point (`npm run refresh-sounds` / `node scripts/...mjs`).
if (import.meta.main) {
  const count = generateSoundsManifest();
  console.log(`[sounds-manifest] Wrote src/data/sounds.generated.ts with ${count} sound${count === 1 ? '' : 's'}.`);
}